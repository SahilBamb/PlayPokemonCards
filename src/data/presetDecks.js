// The 'promo' set (Wizards Black Star Promos + Super Energy Retrieval) covers
// most of the special cards these lists call for: promo Mewtwo, promo Mew,
// promo Venusaur, and Super Energy Retrieval are the real cards. In the 2000
// articles, "Mewtwo" always refers to the movie promo (Energy Absorption /
// Psyburn), so those lists use 'Mewtwo (Promo 3)'. Cards still outside the
// pool are substituted and called out in `note`:
//   Articuno/Moltres (Game Boy exclusives) -> the Fossil prints
// The Japanese vending Gastly & Haunter exist as the 'vending' set.
// The Base–Fossil article's "Turn 1 Zapdos" deck is omitted: it's built
// entirely around the Game Boy-exclusive Zapdos (Peal of Thunder) and plays
// zero energy. Original Rules decks use the international (post-errata) cards
// and rules; the pre-errata mechanics themselves aren't simulated.

