// Generates src/data/baseStats.js from the raw pokemontcg.io dump (scripts/base1_raw.json).
// Run: node scripts/gen_cards.mjs
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const here = path.dirname(fileURLToPath(import.meta.url))
const raw = JSON.parse(fs.readFileSync(path.join(here, 'base1_raw.json'), 'utf8'))

const t = (s) => s.toLowerCase()
const costObj = (arr) => {
  const o = {}
  for (const c of arr || []) {
    const k = t(c)
    o[k] = (o[k] || 0) + 1
  }
  return o
}

const cards = raw.data.map((c) => {
  const base = { name: c.name, number: +c.number, image: c.images?.small || null }
  if (c.supertype === 'Pokémon') {
    return {
      ...base,
      supertype: 'pokemon',
      stage: c.subtypes.includes('Stage 2') ? 'stage2' : c.subtypes.includes('Stage 1') ? 'stage1' : 'basic',
      hp: +c.hp,
      type: t(c.types[0]),
      evolvesFrom: c.evolvesFrom || null,
      weakness: c.weaknesses ? t(c.weaknesses[0].type) : null,
      resistance: c.resistances ? t(c.resistances[0].type) : null,
      retreatCost: c.convertedRetreatCost || 0,
      power: c.abilities ? { name: c.abilities[0].name, text: c.abilities[0].text } : null,
      attacks: (c.attacks || []).map((a) => ({
        name: a.name,
        cost: costObj(a.cost),
        damage: a.damage || '',
        text: a.text || '',
      })),
    }
  }
  if (c.supertype === 'Trainer') {
    return { ...base, supertype: 'trainer', text: (c.rules || []).join(' ') }
  }
  return {
    ...base,
    supertype: 'energy',
    energy: c.name === 'Double Colorless Energy' ? 'doublecolorless' : t(c.name.split(' ')[0]),
    text: (c.rules || []).join(' '),
  }
})

const out = '// Auto-generated by scripts/gen_cards.mjs — do not edit by hand.\nconst BASE_STATS = ' +
  JSON.stringify(cards, null, 1) + '\n\nexport default BASE_STATS\n'
fs.writeFileSync(path.join(here, '..', 'src', 'data', 'baseStats.js'), out)
console.log('Wrote', cards.length, 'cards to src/data/baseStats.js')
